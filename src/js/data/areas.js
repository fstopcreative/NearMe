export const AREAS = LIST.map((a) => ({
  ...a, focus: !!a.focus, city: 'Manchester', id: a.name.toLowerCase().replace(/\s+/g, '-'),
}));

export const findArea = (id) => AREAS.find((a) => a.id === id) || null;

// Area Radar opens on the Trafford borough view when no ?area= is given.
// The figures on the page are Old Trafford (M16), the only fully sourced area.
export const DEFAULT_AREA_ID = 'trafford';
export const currentArea = () =>
  findArea(new URLSearchParams(location.search).get('area')) || findArea(DEFAULT_AREA_ID);

// Location trail for the breadcrumb: UK › Greater Manchester › borough › area.
export const areaTrail = (a) => (a.kind === 'region'
  ? ['UK', 'North West', a.name]
  : a.kind === 'borough'
    ? ['UK', 'Greater Manchester', a.name]
    : ['UK', a.borough === 'Trafford' ? 'Greater Manchester' : a.county, a.borough, a.name]);

// Whole-authority views (borough, region) show authority-wide figures instead of a circle round the centre.
export const isWide = (a) => !!a && (a.kind === 'borough' || a.kind === 'region');

// Production URLs; the dev server maps them onto the source pages (vite.config.js).
export const areaHref = (a) => (a.id === DEFAULT_AREA_ID ? '/' : `/?area=${a.id}`);

// Party Wall page for a focus area (generated by src/seo/townships.py).
export const partyWallHref = (a) => (a && a.focus ? `/party-wall-surveyors/${a.id}` : '/party-wall-surveyors/trafford');
